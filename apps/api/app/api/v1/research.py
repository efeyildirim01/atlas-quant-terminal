"""AI research copilot endpoints. Signed-in users only (cost control, private portfolio tools, audit trail)."""

from __future__ import annotations

import os
from pathlib import Path

from fastapi import APIRouter, Depends, HTTPException, Request
from pydantic import BaseModel, Field
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.ai.copilot import Copilot, CopilotUnavailable, CopilotUpstreamError, make_client
from app.ai.tools import TOOLS, Context
from app.api.v1.common import settings_of
from app.auth.deps import audit, current_user, get_db
from app.models import ResearchQuery, User

router = APIRouter(prefix="/research", tags=["research"])

SETUP_HINT = ("Set ANTHROPIC_API_KEY for the API process (or run `ant auth login` on the server) and restart it. "
              "Credentials are read by the Anthropic SDK; ATLAS never stores them.")


class QueryIn(BaseModel):
    question: str = Field(min_length=3, max_length=2000)
    history_ids: list[str] = Field(default_factory=list, max_length=5)


def credentials_present() -> list[str]:
    found = [v for v in ("ANTHROPIC_API_KEY", "ANTHROPIC_AUTH_TOKEN", "ANTHROPIC_PROFILE") if os.getenv(v)]
    if (Path.home() / ".config" / "anthropic").is_dir():
        found.append("ant profile (~/.config/anthropic)")
    return found


def _client(request: Request):
    factory = getattr(request.app.state, "ai_client_factory", None) or make_client
    return factory()


def _out(q: ResearchQuery) -> dict:
    return {"query_id": q.query_id, "question": q.question, "answer": q.answer, "evidence": q.evidence,
            "verification": q.verification, "model": q.model, "served_by": q.served_by, "stop_reason": q.stop_reason,
            "usage": q.usage, "notes": q.notes, "latency_ms": q.latency_ms, "created_at": q.created_at,
            "disclaimer": "Research assistance generated by an AI model from platform tools. Not investment advice."}


@router.get("/status")
def status(request: Request) -> dict:
    s = settings_of(request)
    creds = credentials_present()
    injected = getattr(request.app.state, "ai_client_factory", None) is not None
    return {"enabled": s.ai_enabled, "configured": s.ai_enabled and (bool(creds) or injected),
            "credential_sources": creds, "model": s.ai_model, "effort": s.ai_effort, "max_rounds": s.ai_max_rounds,
            "setup": SETUP_HINT, "note": "Credentials are checked for presence only; validity is confirmed on the first query.",
            "tools": [{"name": t.name, "description": t.description, "available": not t.unavailable} for t in TOOLS]}


@router.post("/query")
def query(body: QueryIn, request: Request, user: User = Depends(current_user), db: Session = Depends(get_db)) -> dict:
    s = settings_of(request)
    if not s.ai_enabled:
        raise HTTPException(503, "The AI research assistant is disabled (ATLAS_AI_ENABLED=false).")
    metrics = request.app.state.metrics
    if not request.app.state.rate_limiter.allow("ai", user.user_id, s.ai_queries_per_minute):
        metrics.inc("atlas_rate_limited_total", bucket="ai")
        raise HTTPException(429, "Too many research questions this minute.")
    history = []
    if body.history_ids:
        rows = db.scalars(select(ResearchQuery).where(ResearchQuery.query_id.in_(body.history_ids), ResearchQuery.user_id == user.user_id))
        history = [{"question": r.question, "answer": r.answer} for r in sorted(rows, key=lambda r: r.created_at)]
    try:
        copilot = Copilot(_client(request), s.ai_model, s.ai_effort, s.ai_max_rounds)
        result = copilot.run(Context(db, s, user), body.question, history)
    except CopilotUnavailable as exc:
        metrics.inc("atlas_ai_queries_total", result="not_configured")
        raise HTTPException(503, f"AI research assistant is not configured: {exc}. {SETUP_HINT}") from exc
    except CopilotUpstreamError as exc:
        metrics.inc("atlas_ai_queries_total", result=f"upstream_{exc.status}")
        raise HTTPException(exc.status, str(exc)) from exc
    q = ResearchQuery(user_id=user.user_id, question=body.question, answer=result.answer,
                      evidence=[e.public() for e in result.evidence], verification=result.verification, model=result.model,
                      served_by=result.served_by, stop_reason=result.stop_reason,
                      usage={**result.usage, **({"refusal": result.refusal} if result.refusal else {})},
                      notes=result.notes, latency_ms=result.latency_ms)
    db.add(q)
    db.flush()
    metrics.inc("atlas_ai_queries_total", result=result.stop_reason if result.stop_reason == "refusal" else result.verification["status"])
    for kind in ("input_tokens", "output_tokens", "cache_read_input_tokens", "cache_creation_input_tokens"):
        metrics.inc("atlas_ai_tokens_total", float(result.usage.get(kind) or 0), kind=kind.removesuffix("_tokens").removesuffix("_input"))
    audit(db, request, "research.query", user.user_id, q.query_id,
          {"tools": [e.tool for e in result.evidence], "verification": result.verification["status"], "stop_reason": result.stop_reason})
    db.commit()
    return _out(q)


@router.get("/history")
def history(user: User = Depends(current_user), db: Session = Depends(get_db)) -> list[dict]:
    rows = db.scalars(select(ResearchQuery).where(ResearchQuery.user_id == user.user_id).order_by(ResearchQuery.created_at.desc()).limit(50))
    return [{"query_id": r.query_id, "question": r.question, "created_at": r.created_at,
             "verification": r.verification.get("status"), "stop_reason": r.stop_reason} for r in rows]


@router.get("/history/{query_id}")
def history_item(query_id: str, user: User = Depends(current_user), db: Session = Depends(get_db)) -> dict:
    q = db.scalar(select(ResearchQuery).where(ResearchQuery.query_id == query_id, ResearchQuery.user_id == user.user_id))
    if q is None:
        raise HTTPException(404, "Not found")
    return _out(q)
